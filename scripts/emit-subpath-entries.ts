/**
 * Emits the runtime entry files of the subpaths that expose part of the main
 * bundle: dist/<subpath>/index.js (ESM) and dist/<subpath>/index.cjs
 * (CommonJS).
 *
 * These subpaths are views of the main entry, not separate bundles. Building
 * src/components/index.ts on its own would give it a second copy of every
 * React context (PortalContext, SettingsContext, TasksContext), so a hook or
 * component imported from a subpath could not see a provider rendered from
 * the main entry. Instead each entry re-exports names from dist/index.js or
 * dist/index.umd.cjs, and both specifiers load one module instance.
 *
 * The names are the runtime (value) exports of the subpath's declaration
 * file, so an entry exports exactly what its types promise. A name the main
 * bundle doesn't export fails the build here; in the CommonJS entry it also
 * throws on load instead of resolving to undefined. A subpath with only types
 * gets empty entries that never load the main bundle, so
 * `import { type Task } from ".../types"`, which verbatimModuleSyntax keeps
 * as a runtime import, still resolves.
 *
 * Must run AFTER the main `vite build` and `tsc -p tsconfig.build.json`.
 *
 * Usage: tsx scripts/emit-subpath-entries.ts [distDir]   (default: dist)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

/** Subpaths of package.json "exports" served by re-exporting the main bundle. */
export const FACADE_SUBPATHS = ["components", "hooks", "types"] as const;

export interface EmitSubpathEntriesOptions {
  distDir: string;
  /** Package name, used to label the subpath in generated errors */
  packageName: string;
  subpaths: readonly string[];
}

export interface SubpathEntry {
  subpath: string;
  /** Runtime exports re-exported from the main bundle, sorted */
  names: string[];
}

const GENERATED_BY = "// Generated by scripts/emit-subpath-entries.ts.";

const COMPILER_OPTIONS: ts.CompilerOptions = {
  noEmit: true,
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  types: [],
};

/** False for types, and for values re-exported anywhere along the way with `export type`. */
const isRuntimeExport = (checker: ts.TypeChecker, symbol: ts.Symbol) => {
  let current: ts.Symbol | undefined = symbol;
  while (current && current.flags & ts.SymbolFlags.Alias) {
    if (current.declarations?.some(ts.isTypeOnlyImportOrExportDeclaration)) {
      return false;
    }
    current = checker.getImmediateAliasedSymbol(current);
  }
  return current !== undefined && (current.flags & ts.SymbolFlags.Value) !== 0;
};

const runtimeExportsOfDeclarations = (files: string[]): string[][] => {
  const program = ts.createProgram(files, COMPILER_OPTIONS);
  const checker = program.getTypeChecker();
  return files.map((file) => {
    const source = program.getSourceFile(file);
    const moduleSymbol = source && checker.getSymbolAtLocation(source);
    if (!moduleSymbol) {
      throw new Error(`${file} is not an ES module declaration file`);
    }
    return checker
      .getExportsOfModule(moduleSymbol)
      .filter((symbol) => isRuntimeExport(checker, symbol))
      .map((symbol) => symbol.name)
      .sort();
  });
};

const hasModifier = (node: ts.Node, kind: ts.SyntaxKind) =>
  ts.canHaveModifiers(node) &&
  (ts.getModifiers(node)?.some((modifier) => modifier.kind === kind) ?? false);

const declaredNames = (file: string, statement: ts.Statement): string[] => {
  if (ts.isVariableStatement(statement)) {
    return statement.declarationList.declarations.map(({ name }) => {
      if (!ts.isIdentifier(name)) {
        throw new Error(
          `${file} has a destructuring export, which is not supported`,
        );
      }
      return name.text;
    });
  }
  if (
    (ts.isFunctionDeclaration(statement) || ts.isClassDeclaration(statement)) &&
    statement.name
  ) {
    return [statement.name.text];
  }
  return [];
};

/** Export names of a built ES module, read from its top-level statements. */
const bundleExportNames = (file: string): Set<string> => {
  const source = ts.createSourceFile(
    file,
    readFileSync(file, "utf8"),
    ts.ScriptTarget.Latest,
    false,
    ts.ScriptKind.JS,
  );
  const names = source.statements.flatMap((statement): string[] => {
    if (ts.isExportDeclaration(statement)) {
      const clause = statement.exportClause;
      if (!clause) {
        throw new Error(
          `${file} has an \`export * from\` re-export, so its exports can't be listed statically`,
        );
      }
      return ts.isNamedExports(clause)
        ? clause.elements.map((element) => element.name.text)
        : [clause.name.text];
    }
    if (ts.isExportAssignment(statement)) return ["default"];
    if (!hasModifier(statement, ts.SyntaxKind.ExportKeyword)) return [];
    if (hasModifier(statement, ts.SyntaxKind.DefaultKeyword)) {
      return ["default"];
    }
    return declaredNames(file, statement);
  });
  return new Set(names);
};

const renderEsm = (label: string, names: string[]) =>
  names.length === 0
    ? [GENERATED_BY, `// ${label} exports types only.`, "export {};", ""].join(
        "\n",
      )
    : [
        GENERATED_BY,
        `// ${label} re-exports the main bundle, so both`,
        "// share one module instance and its React contexts.",
        "export {",
        ...names.map((name) => `  ${name},`),
        '} from "../index.js";',
        "",
      ].join("\n");

const renderCjs = (label: string, names: string[]) =>
  names.length === 0
    ? [
        '"use strict";',
        GENERATED_BY,
        `// ${label} exports types only.`,
        'Object.defineProperty(exports, "__esModule", { value: true });',
        "",
      ].join("\n")
    : [
        '"use strict";',
        GENERATED_BY,
        `// ${label} re-exports the main bundle, so both`,
        "// share one module instance and its React contexts.",
        'const main = require("../index.umd.cjs");',
        `for (const name of ${JSON.stringify(names)}) {`,
        "  if (!(name in main)) {",
        `    throw new Error(${JSON.stringify(`${label}: dist/index.umd.cjs does not export "`)} + name + ${JSON.stringify('". The package build is incomplete.')});`,
        "  }",
        "}",
        'Object.defineProperty(exports, "__esModule", { value: true });',
        ...names.map((name) => `exports.${name} = main.${name};`),
        "",
      ].join("\n");

export const emitSubpathEntries = ({
  distDir,
  packageName,
  subpaths,
}: EmitSubpathEntriesOptions): SubpathEntry[] => {
  const root = path.resolve(distDir);
  const display = (file: string) =>
    path.relative(path.dirname(root), file) || file;

  const mainBundle = path.join(root, "index.js");
  if (!existsSync(mainBundle)) {
    throw new Error(
      `${display(mainBundle)} does not exist. Run \`vite build\` first.`,
    );
  }
  const declarationFiles = subpaths.map((subpath) => {
    const file = path.join(root, subpath, "index.d.ts");
    if (!existsSync(file)) {
      throw new Error(
        `${display(file)} does not exist. Run \`tsc -p tsconfig.build.json\` first.`,
      );
    }
    return file;
  });

  const bundleNames = bundleExportNames(mainBundle);
  const entries = runtimeExportsOfDeclarations(declarationFiles).map(
    (names, index) => ({ subpath: subpaths[index], names }),
  );

  const missing = entries.flatMap(({ subpath, names }, index) =>
    names
      .filter((name) => !bundleNames.has(name))
      .map(
        (name) =>
          `  ./${subpath}: "${name}" is declared in ${display(declarationFiles[index])} but ${display(mainBundle)} does not export it`,
      ),
  );
  if (missing.length > 0) {
    throw new Error(
      [
        `emit-subpath-entries: ${missing.length} runtime export(s) missing from the main bundle. Export them from src/index.ts:`,
        ...missing,
      ].join("\n"),
    );
  }

  for (const { subpath, names } of entries) {
    const label = `${packageName}/${subpath}`;
    writeFileSync(
      path.join(root, subpath, "index.js"),
      renderEsm(label, names),
    );
    writeFileSync(
      path.join(root, subpath, "index.cjs"),
      renderCjs(label, names),
    );
  }
  return entries;
};

const main = () => {
  const distDir = process.argv[2] ?? "dist";
  const packageJson = path.join(
    path.dirname(path.resolve(distDir)),
    "package.json",
  );
  const { name } = JSON.parse(readFileSync(packageJson, "utf8")) as {
    name?: unknown;
  };
  if (typeof name !== "string") {
    throw new Error(`${packageJson} has no "name"`);
  }
  const entries = emitSubpathEntries({
    distDir,
    packageName: name,
    subpaths: FACADE_SUBPATHS,
  });
  const summary = entries.map(({ subpath, names }) =>
    names.length === 0
      ? `./${subpath} (types only)`
      : `./${subpath} (${names.length} runtime exports)`,
  );
  process.stdout.write(
    `emit-subpath-entries: wrote index.js and index.cjs for ${summary.join(", ")}\n`,
  );
};

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  main();
}
